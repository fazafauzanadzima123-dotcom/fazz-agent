// Public Supabase client identifiers are read from secrets.properties (git-ignored).
// The Gemini API key is NOT here: it only exists as a server-side Supabase secret.
val secrets = Properties().apply {
    val f = rootProject.file("secrets.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(name: String): String = (secrets.getProperty(name) ?: System.getenv(name) ?: "").trim()

